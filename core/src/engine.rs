#[cfg(test)]
mod tests {
    use super::*;
    use crate::ignore::IgnorePatterns;
    use std::fs;
    use tempfile::TempDir;

    #[test]
    fn test_detect_godot() {
        let temp = TempDir::new().unwrap();
        fs::write(temp.path().join("project.godot"), "").unwrap();
        assert_eq!(detect_engine(temp.path()), Some(GameEngine::Godot));
    }

    #[test]
    fn test_detect_unity() {
        let temp = TempDir::new().unwrap();
        fs::create_dir(temp.path().join("ProjectSettings")).unwrap();
        fs::create_dir(temp.path().join("Assets")).unwrap();
        assert_eq!(detect_engine(temp.path()), Some(GameEngine::Unity));
    }

    #[test]
    fn test_detect_unity_missing_assets() {
        let temp = TempDir::new().unwrap();
        fs::create_dir(temp.path().join("ProjectSettings")).unwrap();
        assert_eq!(detect_engine(temp.path()), None);
    }

    #[test]
    fn test_detect_unreal() {
        let temp = TempDir::new().unwrap();
        fs::write(temp.path().join("MyGame.uproject"), "{}").unwrap();
        assert_eq!(detect_engine(temp.path()), Some(GameEngine::Unreal));
    }

    #[test]
    fn test_detect_none() {
        let temp = TempDir::new().unwrap();
        assert_eq!(detect_engine(temp.path()), None);
    }

    #[test]
    fn test_oakignore_contents_not_empty() {
        assert!(!GameEngine::Godot.oakignore_contents().is_empty());
        assert!(!GameEngine::Unity.oakignore_contents().is_empty());
        assert!(!GameEngine::Unreal.oakignore_contents().is_empty());
    }

    /// Godot's `*.import` and `*.uid` sidecars must be versioned: without them a
    /// fresh checkout re-imports everything and resources lose their ids. This
    /// reads the shipped template; a pattern literal wouldn't catch it changing.
    #[test]
    fn test_godot_template_keeps_sidecars_versioned() {
        let patterns = IgnorePatterns::from_patterns(GameEngine::Godot.oakignore_contents());
        for sidecar in ["icon.svg.import", "art/hero.png.import", "player.gd.uid"] {
            assert!(
                !patterns.is_ignored(Path::new(sidecar), false),
                "{sidecar} must stay versioned"
            );
        }
        assert!(patterns.is_ignored(Path::new(".godot"), true));
    }

    #[test]
    fn test_unity_template_keeps_meta_and_build_tooling() {
        let patterns = IgnorePatterns::from_patterns(GameEngine::Unity.oakignore_contents());
        for kept in ["Assets/hero.png.meta", "Assets/BuildTools/Packer.cs"] {
            assert!(!patterns.is_ignored(Path::new(kept), false), "{kept}");
        }
        assert!(patterns.is_ignored(Path::new("Library"), true));
        assert!(patterns.is_ignored(Path::new("game/Library"), true));
    }

    #[test]
    fn test_unreal_template_keeps_content() {
        let patterns = IgnorePatterns::from_patterns(GameEngine::Unreal.oakignore_contents());
        assert!(!patterns.is_ignored(Path::new("Content/Hero.uasset"), false));
        assert!(patterns.is_ignored(Path::new("Intermediate"), true));
        assert!(patterns.is_ignored(Path::new("Plugins/Oak/Binaries"), true));
    }

    #[test]
    fn test_display() {
        assert_eq!(GameEngine::Godot.to_string(), "Godot");
        assert_eq!(GameEngine::Unity.to_string(), "Unity");
        assert_eq!(GameEngine::Unreal.to_string(), "Unreal Engine");
    }
}
